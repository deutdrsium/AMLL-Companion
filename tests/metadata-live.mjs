import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import assert from 'node:assert/strict';
import {createMetadataLookup,resolveMetadata} from '../shared/metadata.mjs';
const run=promisify(execFile), calls=[];
const request=async(url,signal)=>{
 calls.push(url);
 const result=await run('dotnet',['tests/NativeLyricsTests/bin/Release/net10.0/NativeLyricsTests.dll','--json',url],{windowsHide:true,signal,encoding:'utf8',maxBuffer:4*1024*1024});
 return JSON.parse(result.stdout.replace(/^\uFEFF/,''));
};
const lookup=createMetadataLookup(request),catalogueLookup=createMetadataLookup(request,3100);
const storage={getItem:()=>null,setItem:()=>{}};
const music={musicId:'live-test',musicName:'Starry Starry',artists:['hifumi'],albumName:'Starry Starry',duration:257301};
const result=await resolveMetadata(music,new AbortController().signal,{lookup,catalogueLookup,storage});
assert.deepEqual(result.music.artists,['一二三'],result.message);
assert.ok(result.music.artistAliases.some(a=>a.toLowerCase()==='hifumi'));
assert.ok(result.music.metadataArtistIds.includes('9a480ba9-4b92-4096-92de-534f644d2dcc'));
console.log('PASS real MusicBrainz via native HTTP: hifumi → 一二三, recording identity checked; requests='+calls.length);
const moonbath={musicId:'moonbath-test',musicName:'Moonbath',artists:['Yorushika'],albumName:'Moonbath - Single',duration:248000};
const titleResult=await resolveMetadata(moonbath,new AbortController().signal,{lookup,catalogueLookup,storage});
assert.equal(titleResult.music.musicName,'月光浴',titleResult.message);
assert.deepEqual(titleResult.music.artists,['ヨルシカ']);
assert.ok(titleResult.music.titleAliases.includes('Moonbath'));
assert.equal(titleResult.music.metadataRecordingId,'e2655869-e2bd-4125-ae03-2037c2dcb756');
console.log('PASS real MusicBrainz via native HTTP: Moonbath / Yorushika → 月光浴 / ヨルシカ, no hardcoded alias');
const spica={musicId:'spica-test',musicName:'Spica',artists:['上白石萌音'],albumName:'Kibi',duration:316240};
const corrected=await resolveMetadata(spica,new AbortController().signal,{lookup,catalogueLookup,storage});
assert.equal(corrected.music.musicName,'スピカ',corrected.message);
assert.ok(corrected.music.titleAliases.includes('Spica'));
assert.ok(corrected.music.artistAliases.includes('Mone Kamishiraishi'));
assert.equal(corrected.music.metadataReleaseRegion,'JP');
console.log('PASS real regional release metadata: Spica → スピカ, JP release verified, aliases='+JSON.stringify(corrected.music));
